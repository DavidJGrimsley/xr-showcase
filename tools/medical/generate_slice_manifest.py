"""Validate a Slicer export and generate Metro's literal image references (stdlib only)."""

import argparse
import hashlib
import json
import math
from pathlib import Path
import struct
import zlib


def inspect_png(path):
    data = path.read_bytes()
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        raise ValueError(f"Invalid PNG signature: {path.name}")
    offset, dimensions, image_data, ended = 8, None, bytearray(), False
    while offset < len(data):
        if offset + 12 > len(data):
            raise ValueError(f"Truncated PNG: {path.name}")
        length = struct.unpack(">I", data[offset:offset + 4])[0]
        tag = data[offset + 4:offset + 8]
        payload = data[offset + 8:offset + 8 + length]
        crc = data[offset + 8 + length:offset + 12 + length]
        if len(crc) != 4 or zlib.crc32(tag + payload) != struct.unpack(">I", crc)[0]:
            raise ValueError(f"Invalid PNG checksum: {path.name}")
        if tag == b"IHDR":
            if dimensions is not None or offset != 8 or length != 13:
                raise ValueError(f"Invalid PNG header: {path.name}")
            width, height, depth, color, compression, filtering, interlace = struct.unpack(">IIBBBBB", payload)
            if width < 1 or height < 1 or (depth, color, compression, filtering, interlace) != (8, 0, 0, 0, 0):
                raise ValueError(f"Expected non-interlaced 8-bit grayscale PNG: {path.name}")
            dimensions = (width, height)
        elif tag == b"IDAT":
            image_data.extend(payload)
        elif tag == b"IEND":
            ended = True
            offset += 12 + length
            break
        offset += 12 + length
    if not ended or offset != len(data) or dimensions is None:
        raise ValueError(f"Incomplete PNG: {path.name}")
    pixels = zlib.decompress(image_data)
    width, height = dimensions
    if len(pixels) != height * (width + 1) or any(pixels[row * (width + 1)] > 4 for row in range(height)):
        raise ValueError(f"Invalid PNG pixels: {path.name}")
    return dimensions, len(data), hashlib.sha256(data).hexdigest()


def validate_export(directory):
    directory = Path(directory)
    metadata = json.loads((directory / "metadata.json").read_text(encoding="utf-8"))
    if metadata.get("schemaVersion") != 1 or metadata.get("coordinateSystem") != "RAS mm":
        raise ValueError("Unsupported metadata version or coordinate system")
    series = metadata.get("series")
    if not isinstance(series, list) or not series:
        raise ValueError("No exported slice series")
    seen = set()
    total = 0
    for item in series:
        modality, orientation = item.get("modality"), item.get("orientation")
        if modality not in ("ct", "mri") or orientation != "axial" or (modality, orientation) in seen:
            raise ValueError("Invalid or duplicate series")
        seen.add((modality, orientation))
        slices = item.get("slices", [])
        if not slices or item.get("imageCount") != len(slices):
            raise ValueError("Image count does not match slices")
        previous = -math.inf
        series_bytes = 0
        for index, image in enumerate(slices):
            expected = f"{modality}_{orientation}_{index:03d}.png"
            if image.get("filename") != expected:
                raise ValueError(f"Expected {expected}")
            position = image.get("positionMm")
            if not isinstance(position, (int, float)) or not math.isfinite(position) or position <= previous:
                raise ValueError("Slice coordinates must be finite and strictly increasing")
            previous = position
            dimensions, size, digest = inspect_png(directory / expected)
            if list(dimensions) != item.get("imageDimensions"):
                raise ValueError(f"Image dimensions do not match metadata: {expected}")
            if image.get("bytes") != size or image.get("sha256") != digest:
                raise ValueError(f"Image size/hash does not match metadata: {expected}")
            series_bytes += size
        if series_bytes != item.get("bytes"):
            raise ValueError("Series byte total does not match images")
        total += series_bytes
    if total != metadata.get("imageBytes"):
        raise ValueError("Export byte total does not match images")
    return metadata


def generate_manifest(directory):
    directory = Path(directory)
    metadata = validate_export(directory)
    lines = ["// Generated by tools/medical/generate_slice_manifest.py. Do not edit.",
             "export const medicalSliceSources: Record<string, readonly number[]> = {"]
    for series in metadata["series"]:
        lines.append(f"  '{series['modality']}:{series['orientation']}': [")
        lines.extend(f"    require('./{image['filename']}')," for image in series["slices"])
        lines.append("  ],")
    lines.extend(["};", ""])
    output = directory / "sources.native.ts"
    temporary = output.with_suffix(".tmp")
    with temporary.open("w", encoding="utf-8", newline="\n") as generated_file:
        generated_file.write("\n".join(lines))
    temporary.replace(output)
    return metadata


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("directory", type=Path)
    args = parser.parse_args()
    result = generate_manifest(args.directory)
    print(f"Validated {sum(item['imageCount'] for item in result['series'])} slices; {result['imageBytes']} PNG bytes")
